/* =============================================================================
 * Shared type definitions: chess game state, engine evaluation, UCI messages
 * and the typed message protocol between the React UI and the engine Worker.
 * ========================================================================== */

import type { Color, PieceSymbol, Square } from 'chess.js';

export type { Color, PieceSymbol, Square };

/* ------------------------------------------------------------------ Game */

export type PromotionPiece = 'q' | 'r' | 'b' | 'n';

/** A move expressed in long algebraic / UCI notation, e.g. `e2e4`, `e7e8q`. */
export type UciMove = string;

export interface MoveRecord {
  san: string;
  uci: UciMove;
  from: Square;
  to: Square;
  color: Color;
  /** FEN of the position *after* this move. */
  fenAfter: string;
}

export type GameOverReason =
  | 'checkmate'
  | 'stalemate'
  | 'fifty-move'
  | 'threefold'
  | 'insufficient'
  | 'resign';

export interface GameResult {
  reason: GameOverReason;
  /** `null` = draw. */
  winner: Color | null;
}

export interface GameState {
  fen: string;
  turn: Color;
  history: MoveRecord[];
  inCheck: boolean;
  result: GameResult | null;
}

/* ------------------------------------------------------------- Difficulty */

export type LevelId = 1 | 2 | 3 | 4;

export interface DifficultyLevel {
  id: LevelId;
  name: string;
  description: string;
  /** Default depth sent with `go depth N`. */
  depth: number;
  /** Optional adjustable depth range (Grandmaster level: 16 – 20). */
  range?: readonly [number, number];
}

/* ------------------------------------------------------------ Evaluation */

/** Score as reported by UCI (`score cp N` / `score mate N`). */
export type UciScore =
  | { kind: 'cp'; value: number }
  | { kind: 'mate'; value: number };

/** Parsed `info ...` line. */
export interface UciInfo {
  depth?: number;
  seldepth?: number;
  multipv?: number;
  /** Score from the SIDE-TO-MOVE perspective (raw UCI semantics). */
  score?: UciScore;
  bound?: 'lowerbound' | 'upperbound';
  nodes?: number;
  nps?: number;
  time?: number;
  hashfull?: number;
  pv?: UciMove[];
}

/** Parsed `bestmove X [ponder Y]` line. */
export interface UciBestMove {
  bestmove: UciMove | null; // `(none)` → null (mate / stalemate on board)
  ponder?: UciMove;
}

/** Evaluation normalised to WHITE's perspective, ready for the UI. */
export interface EngineEvaluation {
  score: UciScore;
  depth: number;
  seldepth?: number;
  nodes: number;
  nps: number;
  timeMs: number;
  pv: UciMove[];
  /** Best move predicted at the current depth (first PV move). */
  bestMove: UciMove | null;
  /** FEN the evaluation belongs to. */
  fen: string;
}

/* ------------------------------------------------- Worker ⇄ UI protocol */

/** What a search is for: the AI's real move, or background analysis of the user's position. */
export type SearchPurpose = 'play' | 'analysis';

export interface SearchRequest {
  /** Monotonic id generated by the UI. Every reply carries it back. */
  id: number;
  fen: string;
  /** Optional UCI move list from startpos (`position startpos moves ...`). */
  moves?: UciMove[];
  depth: number;
  purpose: SearchPurpose;
}

/** Messages sent from the UI → Worker. */
export type WorkerInbound =
  /**
   * `engineUrl`: absolute URL of `public/stockfish/stockfish.js` (resolved by the UI
   * so it respects Vite's `base`). `debug`: mirror every UCI line as a `log` message.
   */
  | { type: 'init'; engineUrl: string; debug?: boolean }
  | { type: 'search'; request: SearchRequest }
  /** Abort the current search (sends UCI `stop`), result is discarded. */
  | { type: 'stop' }
  /** Abort + `ucinewgame` + `isready` sync (clears hash tables). */
  | { type: 'newgame' }
  | { type: 'setoption'; name: string; value: string | number | boolean }
  /** Escape hatch: raw UCI command. */
  | { type: 'raw'; command: string }
  | { type: 'quit' };

export type EnginePhase =
  | 'loading' // engine script / wasm downloading
  | 'handshake' // `uci` sent, waiting for `uciok` / `readyok`
  | 'idle' // ready, no search running
  | 'searching' // `go` sent, forwarding info lines
  | 'stopping' // `stop` sent, waiting for the stale `bestmove` to drain
  | 'syncing' // `isready` sent after `ucinewgame`, waiting for `readyok`
  | 'error';

export interface EngineIdentity {
  name: string;
  author: string;
}

/** Messages sent from the Worker → UI. */
export type WorkerOutbound =
  | { type: 'status'; phase: EnginePhase }
  | { type: 'ready'; engine: EngineIdentity }
  /** Raw `info ...` text of the ACTIVE search (parsed on the UI side by `useStockfish`). */
  | { type: 'info'; id: number; fen: string; line: string }
  /** Raw `bestmove ...` text of the ACTIVE search. Stale bestmoves are never forwarded. */
  | { type: 'bestmove'; id: number; fen: string; purpose: SearchPurpose; line: string }
  | { type: 'log'; direction: 'in' | 'out'; line: string }
  | { type: 'error'; message: string };
